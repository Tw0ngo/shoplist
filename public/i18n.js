function t(key, vars = {}) {
  const s = I18N[lang][key] ?? I18N.de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

// static texts: data-t (text), data-t-placeholder, data-t-aria
function translatePage() {
  document.documentElement.lang = lang;
  for (const e of document.querySelectorAll('[data-t]')) e.textContent = t(e.dataset.t);
  for (const e of document.querySelectorAll('[data-t-placeholder]')) e.placeholder = t(e.dataset.tPlaceholder);
  for (const e of document.querySelectorAll('[data-t-aria]')) e.setAttribute('aria-label', t(e.dataset.tAria));
}

function setLang(l) {
  if (!I18N[l]) return;
  lang = l;
  try { localStorage.setItem('shop.lang', l); } catch {}
  translatePage();
}

async function request(method, url, body, headers = {}) {
  let r;
  try {
    r = await fetch(url, { method, headers: { 'X-Shop': '1', ...(body ? { 'Content-Type': 'application/json' } : {}), ...headers }, body: body && JSON.stringify(body) });
  } catch { throw new Error(t('err.offline')); }
  // HTML instead of JSON: a proxy in front wants something first (bot check, sign-in); let the page load it again
  if (!(r.headers.get('content-type') || '').includes('application/json')) { location.reload(); throw new Error(t('err.reload')); }
  const data = await r.json().catch(() => ({}));
  if (!r.ok) {
    const msg = data.error && I18N[lang]['err.' + data.error] ? t('err.' + data.error) : t('err.status', { n: r.status });
    throw Object.assign(new Error(msg), { status: r.status, code: data.error });
  }
  return data;
}

